from datetime import datetime
from typing import Literal, Optional
from pydantic import BaseModel, Field, field_validator


class ReviewInput(BaseModel):
    text: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description="Customer review text",
        examples=["The product is great, fast delivery!"],
    )
    product: Optional[str] = Field(
        default=None,
        max_length=200,
        description="Product name or model (optional)",
        examples=["Bluetooth Headphones Pro"],
    )

    @field_validator("text")
    @classmethod
    def validate_non_empty_text(cls, value: str) -> str:
        trimmed = value.strip()
        if len(trimmed) < 3:
            raise ValueError("Review text cannot be empty or only whitespace.")
        return trimmed


class ReviewOutput(BaseModel):
    id: str = Field(..., description="Unique BSON ID generated by MongoDB")
    text: str = Field(..., description="Submitted review text")
    product: Optional[str] = Field(None, description="Product name")
    sentiment: Literal["positive", "negative"] = Field(..., description="Predicted sentiment class")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model prediction confidence (0.0 to 1.0)")
    model: str = Field(..., description="Inference model identifier")
    date: datetime = Field(..., description="UTC timestamp of inference and storage")


class HealthOutput(BaseModel):
    status: Literal["ok", "error"]
    database: bool = Field(..., description="MongoDB connectivity status")
    model: bool = Field(..., description="Memory status of the loaded .joblib model")
